export function translateText(message: string, messages: Messages): string {
  const key = serverMessageKeys[message];
  return key ? messages.errors[key] : message;
}

export function translateError(code: string | undefined, message: string, messages: Messages): string {
  if (code && errorCodeKeys[code]) {
    return messages.errors[errorCodeKeys[code]];
  }
  return translateText(message, messages);
}
